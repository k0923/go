package dflow

import (
	"context"
)

// Resume drives exactly one node for the specified current suspension token.
// Wakeup must have durably delivered its response first. A stale token or
// undelivered response drives nothing. It never drives another suspension round.
// Downstream Ready nodes are handled by the caller just as with Drive.
func (e *Engine) Resume(ctx context.Context, nodeID, token string) (Executed, error) {
	if nodeID == "" || token == "" {
		return Executed{}, ErrWaitNotFound
	}
	return e.drive(ctx, nodeID, token)
}

// Wakeup persists a callback and its wake notification atomically, without taking
// a node lease. token is generated by the engine and delivered with the Request
// notification; it is not a name chosen by node code. After Wakeup the node
// becomes drivable again, so the caller subsequently calls Drive to run Resume.
//
// A duplicate or stale callback returns false; an unknown node/token returns
// ErrWaitNotFound. Delivering a nil response is valid: pass a nil value.
func (e *Engine) Wakeup(ctx context.Context, nodeID, token string, response any) (bool, error) {
	if nodeID == "" || token == "" {
		return false, ErrWaitNotFound
	}
	accepted, err := e.infra.Resolve(ctx, nodeID, token, response)
	if err != nil {
		return false, &InfrastructureError{Op: "Resolve", Cause: err}
	}
	return accepted, nil
}
